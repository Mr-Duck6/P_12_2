class Movie {
  final int id;
  final String title;
  final String description;
  final String posterUrl;
  final double rating;
  final String year;
  final String genre;
  final String director;

  const Movie({
    required this.id,
    required this.title,
    required this.description,
    required this.posterUrl,
    required this.rating,
    required this.year,
    required this.genre,
    required this.director,
  });
}
